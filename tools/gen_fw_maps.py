#!/usr/bin/env python3
"""gen_fw_maps.py - the checked address map of every non-reference firmware build (firmware/<id>/addrmap.json).

Lists every stock address Kraken uses - in the production patch sources (the blobs' sources, linker scripts and the
headers beside them), the generated manifests of image.json and the QEMU tests (tests/*.py except the host tests
test_*.py) - and translates each one into each build with tools/fwmap.py. A value that fwmap cannot prove takes its
translation from firmware/<id>/overrides.json (each with a reason a person checked); one that is a number, not an
address, is listed in firmware/not_addresses.json. Anything else is unresolved and the run fails, listing where the
value is used.

  python3 tools/gen_fw_maps.py                  write firmware/<id>/addrmap.json for every build
  python3 tools/gen_fw_maps.py --check          fail if a map is stale (tools/build_image.py runs this)
  python3 tools/gen_fw_maps.py l01 --report     also print every translation that is not the same address

Needs the stock images (python3 tools/fetch_stock.py) and dm32uv-re's meta/ (functions and disassembly).
"""
import argparse
import collections
import json
import pathlib
import sys

import fw_text
import fwmap
import fwreg

REPO = fwreg.REPO
FWDIR = REPO / "firmware"


def image_cfg():
    return json.loads((REPO / "image.json").read_text())


def manifests():
    """(path, manifest) of every patch in image.json, in order."""
    out = []
    for p in image_cfg()["patches"]:
        rel = pathlib.PurePosixPath(p["manifest"])
        # image.json paths are relative to the folder above the repo, which the build mounts as /w/dm32uv-unleashed
        path = REPO.joinpath(*rel.parts[1:]) if rel.parts[0] in (REPO.name, "dm32uv-unleashed") else REPO.parent / rel
        out.append((path, json.loads(path.read_text())))
    return out


def source_files():
    """The patch source files that go into the production image: blob and pack sources, linker scripts, headers beside them."""
    files = set()
    for path, m in manifests():
        d = path.parent
        for b in m.get("blobs", []):
            files.update((d / s).resolve() for s in b["sources"])
            if "linker_script" in b:
                files.add((d / b["linker_script"]).resolve())
        for s in m.get("pack", {}).get("sources", []):      # kraken_ui: one link, placed by tools/pack_kraken.py
            files.add((d / s["file"]).resolve())
        files.update(p.resolve() for p in d.glob("*.h"))
    return sorted(files)


def test_files():
    return sorted(p for p in (REPO / "tests").glob("*.py") if not p.name.startswith("test_"))


def inventory():
    """{value: set(repo-relative files)}"""
    inv = collections.defaultdict(set)
    for f in source_files() + test_files():
        for _s, _e, v, _f in fw_text.spans(f, f.read_text()):
            inv[v].add(str(f.relative_to(REPO)))
    for path, m in manifests():
        for v in fw_text.json_values(m):
            inv[v].add(str(path.relative_to(REPO)))
    return inv


def not_addresses():
    p = FWDIR / "not_addresses.json"
    return {int(k, 16): why for k, why in json.loads(p.read_text())["values"].items()} if p.exists() else {}


def overrides(fw):
    p = FWDIR / fw["id"] / "overrides.json"
    if not p.exists():
        return {}
    doc = json.loads(p.read_text())
    out = {}
    for k, o in doc["overrides"].items():
        if len(o.get("why", "")) < 20:
            sys.exit(f"{p}: override {k} needs a reason (why, at least 20 characters)")
        out[int(k, 16)] = (int(o["to"], 16), "override: " + o["why"])
    return out


def build_map(fw, inv, report=False):
    m = fwmap.FwMap(fw)
    nums, ovr = not_addresses(), overrides(fw)
    table, bad = {}, []
    for v in sorted(inv):
        if v in nums:
            continue
        if v in ovr:
            to, how = ovr[v]
        else:
            try:
                to, how = m.translate(v)
            except fwmap.Unresolved as e:
                bad.append((v, str(e)))
                continue
        table[v] = (to, how)
    unused = sorted(set(ovr) - set(inv))
    doc = {
        "_comment": [
            f"GENERATED by tools/gen_fw_maps.py - do not edit. Every stock address Kraken uses, translated from the reference "
            f"build {fwreg.reference()['version']} into {fw['version']}, and how each translation was proved.",
            "Overrides (reviewed by hand) are in overrides.json beside this file; numbers that are not addresses in "
            "../not_addresses.json. docs/firmware-builds.md explains the methods.",
        ],
        "firmware": fw["version"],
        "reference": fwreg.reference()["version"],
        "reference_sha256": fwreg.sha256(m.ref.img),
        "target_sha256": fwreg.sha256(m.img),
        "functions": m.summary(),
        "map": {f"{v:#010x}": {"to": f"{to:#010x}", "how": how, "in": sorted(inv[v])} for v, (to, how) in table.items()},
    }
    if report:
        print(f"== {fw['id']}: translations that move ==")
        for v, (to, how) in table.items():
            if to != v:
                print(f"  {v:#010x} -> {to:#010x} {to - v:+#x}  {how}   [{', '.join(sorted(inv[v]))}]")
    return doc, bad, unused


def write(path, doc):
    return json.dumps(doc, indent=1) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("ids", nargs="*")
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--report", action="store_true")
    a = ap.parse_args()
    inv = inventory()
    failed = False
    for fw in fwreg.firmwares()[1:]:
        if a.ids and fw["id"] not in a.ids:
            continue
        doc, bad, unused = build_map(fw, inv, a.report)
        out = FWDIR / fw["id"] / "addrmap.json"
        text = write(out, doc)
        for v in unused:
            print(f"{fw['id']}: override {v:#010x} is no longer used anywhere: remove it", file=sys.stderr)
            failed = True
        if bad:
            failed = True
            print(f"{fw['id']}: {len(bad)} addresses could not be translated into {fw['version']}:", file=sys.stderr)
            for v, why in bad:
                print(f"  {v:#010x}  {why}\n      used in {', '.join(sorted(inv[v]))}", file=sys.stderr)
            print(f"  Prove each one by hand and add it to firmware/{fw['id']}/overrides.json, or list a number that "
                  f"is not an address in firmware/not_addresses.json.", file=sys.stderr)
            continue
        if a.check:
            if not out.exists() or out.read_text() != text:
                print(f"{out.relative_to(REPO)} is stale: run python3 tools/gen_fw_maps.py", file=sys.stderr)
                failed = True
            continue
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(text)
        moved = sum(1 for e in doc["map"].values() if e["to"] != e.get("from"))
        print(f"{fw['id']}: {len(doc['map'])} addresses -> {out.relative_to(REPO)}")
    sys.exit(1 if failed else 0)


if __name__ == "__main__":
    main()
