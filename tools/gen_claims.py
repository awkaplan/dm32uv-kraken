#!/usr/bin/env python3
"""Generate patches/kraken_ui/krk_claims.h, the C view of this repo's PINNED claims, from allocations.json.

Kraken's code and most of its state are placed per build by tools/pack_kraken.py (docs/flash-allocation.md); allocations.json
keeps only the claims that must sit at a fixed address because something reaches them by address rather than by symbol: the
menu data sector (manifest data items), the shared F9/F13 buffer (the mi_rng measurement build taps it), the APRS inbox and the
mi_rng pool (shared with patches/mi_rng), and the bench build's claims. Each becomes
  KRK_<NAME>_LO / KRK_<NAME>_HI_EXCL     <NAME> = the claim name without its "kraken_" prefix, upper case
(kraken_aprs_inbox -> KRK_APRS_INBOX_LO).

Usage:
  tools/gen_claims.py           rewrite the header
  tools/gen_claims.py --check   exit 1 if it is out of date (build_image.py runs this)
"""
import argparse
import json
import pathlib
import sys

REPO = pathlib.Path(__file__).resolve().parent.parent
ALLOC = REPO / "allocations.json"
HEADER = REPO / "patches/kraken_ui/krk_claims.h"

def macro(name):
    return "KRK_" + name.removeprefix("kraken_").upper()


def build():
    claims = json.loads(ALLOC.read_text())["allocations"]
    by = {c["name"]: c for c in claims}
    lines = []
    for sp in ("flash", "sram"):
        lines.append(f"/* {sp} */")
        for c in claims:
            if c["space"] != sp:
                continue
            m = macro(c["name"])
            lines.append(f"{'#define ' + m + '_LO':<36}{c['start']}u")
            lines.append(f"{'#define ' + m + '_HI_EXCL':<36}{c['end_exclusive']}u")
        lines.append("")
    return "\n".join([
        "/* krk_claims.h - GENERATED by tools/gen_claims.py from allocations.json. Do not edit: change the claim there and",
        " * rerun the script (the build fails while this file is out of date). One _LO / _HI_EXCL pair per pinned claim.",
        " * C only (the u suffixes). */",
        "#ifndef KRK_CLAIMS_H",
        "#define KRK_CLAIMS_H",
        "",
        *lines,
        "",
        "#endif",
        ""])


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--check", action="store_true", help="fail if the header is out of date")
    args = ap.parse_args()
    outs = [(HEADER, HEADER.read_text() if HEADER.exists() else "", build())]
    stale = [p for p, old, new in outs if old != new]
    if args.check:
        if stale:
            print(f"gen_claims: out of date with {ALLOC.name}: {', '.join(p.name for p in stale)}; run tools/gen_claims.py",
                  file=sys.stderr)
            return 1
        return 0
    for p, old, new in outs:
        if old != new:
            p.write_text(new)
    print(f"gen_claims: {'updated ' + ', '.join(p.name for p in stale) if stale else 'up to date'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
