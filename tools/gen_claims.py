#!/usr/bin/env python3
"""Generate patches/kraken_ui/krk_claims.h (and the KRK_EXT* region of krk.h), the C view of this repo's claims, from allocations.json.

allocations.json is the one place the claims are written down (the builder and tools/build_image.py read it). The C side used to
copy the numbers (krk.h KRK_EXT_LO/HI ...) and could drift from it; now every claim becomes
  KRK_<NAME>_LO / KRK_<NAME>_HI_EXCL     <NAME> = the claim name without its "kraken_" prefix, upper case
(kraken_ui_code2 -> KRK_UI_CODE2_LO), plus the fixed-offset addresses a blob's linker script pins inside its claim (OFFSETS below).
krk.h keeps the historical KRK_EXT*_LO/HI names (LEGACY below) as plain literals in a region between two marker comments that this
script rewrites too: tests/ read those names out of krk.h's text with a regex, so they cannot be aliases of the generated macros.

Usage:
  tools/gen_claims.py           rewrite the header
  tools/gen_claims.py --check   exit 1 if it is out of date (build_image.py runs this)
"""
import argparse
import json
import pathlib
import sys

REPO = pathlib.Path(__file__).resolve().parent.parent
ALLOC = REPO / "allocations.json"
HEADER = REPO / "patches/kraken_ui/krk_claims.h"
KRK_H = REPO / "patches/kraken_ui/krk.h"
BEGIN = "/* BEGIN generated by tools/gen_claims.py: do not edit (see krk_claims.h) */"
END = "/* END generated by tools/gen_claims.py */"

# (macro, claim, "start" | "end_exclusive", comment): the names krk.h and the C sources have always used for the extension ranges
LEGACY = [("KRK_EXT_LO", "kraken_ui_code2", "start", ""),
          # until 2026-11-06 this was a hand-copied 0x030f8000, stale since the 2026-10-30 shrink gave 0x030f7000-0x030f8000
          # away: ext_ok() and krk_ext_hook() then accepted pointers past the blob. Now the claim end.
          ("KRK_EXT_HI", "kraken_ui_code2", "end_exclusive", "= kraken_ui_code2 end; krk_core rejects any screen or label at or past it"),
          ("KRK_EXT3_LO", "kraken_ui3_code", "start", "kraken_ui3 (F10 satellite blob): screens there may sit in the table too"),
          ("KRK_EXT3_HI", "kraken_ui3_code", "end_exclusive", ""),
          ("KRK_EXT4_LO", "kraken_ui4_code", "start", "kraken_ui4 (F13 burst voice blob): likewise"),
          ("KRK_EXT4_HI", "kraken_ui4_code", "end_exclusive", ""),
          ("KRK_EXT5_LO", "kraken_ui5_code", "start", "kraken_ui5 (F3 DMR link blob, dm32uv-re's reclaimed ramdump_probe_code sector): likewise"),
          ("KRK_EXT5_HI", "kraken_ui5_code", "end_exclusive", "")]

# (macro, claim, offset into the claim, why): addresses fixed by a linker script, read by code built in an earlier blob
OFFSETS = [("KRK_UI4_HOOK_TABLE", "kraken_ui4_code", 0x20,
            "one-entry TX-watchdog hook table right behind the screen descriptor (kraken_ui4.ld), read by krk_periodic.c")]


def macro(name):
    return "KRK_" + name.removeprefix("kraken_").upper()


def build_region():
    by = {c["name"]: c for c in json.loads(ALLOC.read_text())["allocations"]}
    return "\n".join([BEGIN, *(f"{'#define ' + m:<20}{by[c][k]}u" + (f"    /* {w} */" if w else "") for m, c, k, w in LEGACY), END])


def build():
    claims = json.loads(ALLOC.read_text())["allocations"]
    by = {c["name"]: c for c in claims}
    lines = []
    for sp in ("flash", "sram"):
        lines.append(f"/* {sp} */")
        for c in claims:
            if c["space"] != sp:
                continue
            m = macro(c["name"])
            lines.append(f"{'#define ' + m + '_LO':<36}{c['start']}u")
            lines.append(f"{'#define ' + m + '_HI_EXCL':<36}{c['end_exclusive']}u")
        lines.append("")
    lines.append("/* fixed offsets inside a claim */")
    for m, claim, off, why in OFFSETS:
        lo = int(by[claim]["start"], 0)
        hi = int(by[claim]["end_exclusive"], 0)
        if not lo + off < hi:
            raise SystemExit(f"gen_claims: {m} lies outside {claim}")
        lines.append(f"#define {m} ({macro(claim)}_LO + {off:#x}u)    /* {why} */")
    return "\n".join([
        "/* krk_claims.h - GENERATED by tools/gen_claims.py from allocations.json. Do not edit: change the claim there and",
        " * rerun the script (the build fails while this file is out of date). One _LO / _HI_EXCL pair per claim; krk.h",
        " * maps the KRK_EXT*_LO/HI names onto them. C only (the u suffixes). */",
        "#ifndef KRK_CLAIMS_H",
        "#define KRK_CLAIMS_H",
        "",
        *lines,
        "",
        "#endif",
        ""])


def splice_region(text, region):
    a, b = text.find(BEGIN), text.find(END)
    if a < 0 or b < a:
        raise SystemExit(f"gen_claims: {KRK_H.name} has no '{BEGIN}' ... END region")
    return text[:a] + region + text[b + len(END):]


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--check", action="store_true", help="fail if the header is out of date")
    args = ap.parse_args()
    outs = [(HEADER, HEADER.read_text() if HEADER.exists() else "", build())]
    uh = KRK_H.read_text()
    outs.append((KRK_H, uh, splice_region(uh, build_region())))
    stale = [p for p, old, new in outs if old != new]
    if args.check:
        if stale:
            print(f"gen_claims: out of date with {ALLOC.name}: {', '.join(p.name for p in stale)}; run tools/gen_claims.py",
                  file=sys.stderr)
            return 1
        return 0
    for p, old, new in outs:
        if old != new:
            p.write_text(new)
    print(f"gen_claims: {'updated ' + ', '.join(p.name for p in stale) if stale else 'up to date'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
