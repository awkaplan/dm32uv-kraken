#!/usr/bin/env python3
"""Turn data/tles.txt into patches/kraken_ui/krk_sat_tles.c (const TLE table compiled into the F10 blob).

Usage: python3 tools/sat_tle_gen.py [data/tles.txt] [patches/kraken_ui/krk_sat_tles.c]
Deterministic: the output depends only on the input text (no dates, no host state). The build does NOT run it;
run it after editing the text file, review the diff, then rebuild (docs/satellite-mode.md "Implementation").

Input: '#' comments, blank lines, and records
    @ NAME dl_mhz ul_mhz pl_hz [free-text note]
    <TLE line 1>
    <TLE line 2>
dl = satellite downlink (the radio's RX), ul = satellite uplink (radio TX; 0 = none), pl = uplink CTCSS tone (0 = none).
Checks: name <= 11 chars, both lines 69 columns, modulo-10 checksums, line numbers, equal catalog numbers, mean motion
> 6.4 rev/day (near-earth only: krk_sat.c has no SDP4), at most MAX records.
"""
import pathlib
import sys

MAX = 10
REPO = pathlib.Path(__file__).resolve().parents[1]


def checksum(line):
    return sum(int(c) if c.isdigit() else (1 if c == "-" else 0) for c in line[:68]) % 10


def parse(text):
    recs, cur, lines = [], None, []
    for n, raw in enumerate(text.splitlines(), 1):
        s = raw.rstrip()
        if not s or s.startswith("#"):
            continue
        if s.startswith("@"):
            if cur and len(lines) != 2:
                sys.exit(f"{cur[0]}: expected 2 TLE lines")
            f = s[1:].split(None, 4)
            if len(f) < 4:
                sys.exit(f"line {n}: '@ NAME dl ul pl [note]'")
            cur = [f[0], round(float(f[1]) * 1e6), round(float(f[2]) * 1e6), round(float(f[3]) * 10)]
            recs.append(cur)
            lines = []
            continue
        if cur is None:
            sys.exit(f"line {n}: TLE line before any '@' record")
        lines.append(s)
        cur.append(s)
        if len(lines) > 2:
            sys.exit(f"{cur[0]}: more than 2 TLE lines")
    return recs


def validate(r):
    name, dl, ul, pl, l1, l2 = r
    if len(name) > 11 or not name.isascii():
        sys.exit(f"{name}: name must be <= 11 ASCII characters")
    for i, l in enumerate((l1, l2), 1):
        if len(l) != 69 or l[0] != str(i) or int(l[68]) != checksum(l):
            sys.exit(f"{name}: TLE line {i} bad (69 columns, line number, checksum)")
    if l1[2:7] != l2[2:7]:
        sys.exit(f"{name}: catalog numbers differ")
    if float(l2[52:63]) <= 6.4:
        sys.exit(f"{name}: period >= 225 min is not near-earth (krk_sat.c has no SDP4)")
    if not (dl and 100e6 < dl < 500e6) or not (ul == 0 or 100e6 < ul < 500e6):
        sys.exit(f"{name}: frequencies out of range")


def main():
    src = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else REPO / "data/tles.txt"
    dst = pathlib.Path(sys.argv[2]) if len(sys.argv) > 2 else REPO / "patches/kraken_ui/krk_sat_tles.c"
    recs = parse(src.read_text())
    if not recs or len(recs) > MAX:
        sys.exit(f"need 1..{MAX} records, got {len(recs)}")
    for r in recs:
        if len(r) != 6:
            sys.exit(f"{r[0]}: expected 2 TLE lines")
        validate(r)
    o = ["/* GENERATED by tools/sat_tle_gen.py from data/tles.txt: do not edit. Refresh TLEs and frequencies before use. */",
         '#include "krk_satdb.h"', "",
         "const struct krk_sat_tle krk_sat_tles[] = {"]
    for name, dl, ul, pl, l1, l2 in recs:
        o.append(f'    {{ "{name}", {dl}u, {ul}u, {pl},')
        o.append(f'      "{l1}",')
        o.append(f'      "{l2}" }},')
    o += ["};", f"const unsigned krk_sat_ntles = {len(recs)};", ""]
    dst.write_text("\n".join(o))
    print(f"{dst}: {len(recs)} satellites")


if __name__ == "__main__":
    main()
